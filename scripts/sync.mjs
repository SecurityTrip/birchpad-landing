// Builds the pages that come from Birchpad's own repository, so that they follow it without
// edits here: the changelog, the keyboard shortcuts and the languages. Runs before every build.
//
// Sources are read from GitHub (BIRCHPAD_REF, `main` by default), or from a local checkout when
// BIRCHPAD_DIR is set. When GitHub cannot be reached, pages generated before are kept.
import { mkdir, readFile, writeFile, access } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "smol-toml";
import YAML from "yaml";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = join(ROOT, "src/content/docs");
const REPO = "SecurityTrip/Birchpad";
const REF = process.env.BIRCHPAD_REF || "main";

async function source(path) {
  if (process.env.BIRCHPAD_DIR) return readFile(join(process.env.BIRCHPAD_DIR, path), "utf8");
  const res = await fetch(`https://raw.githubusercontent.com/${REPO}/${REF}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.text();
}

async function write(path, text) {
  const file = join(DOCS, path);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, text);
}

const exists = (path) => access(join(DOCS, path)).then(() => true, () => false);
const yaml = (s) => JSON.stringify(s);
const cell = (s) => String(s).replace(/\|/g, "\\|");
const GENERATED = "<!-- Generated by scripts/sync.mjs from the Birchpad repository. Do not edit. -->";

// --- Changelog -----------------------------------------------------------------------------

function changelog(text, lang) {
  // From the first version on; an empty Unreleased section is left out.
  let body = text.slice(text.indexOf("\n## ") + 1);
  body = body.replace(/^## \[Unreleased\]\s*\n(?=## )/m, "");
  // "## [0.1.4] - 2026-10-12" reads better as "## 0.1.4 · 2026-10-12".
  body = body.replace(/^## \[([^\]]+)\] - (\S+)/gm, "## $1 · $2");
  const head = lang === "ru"
    ? {
        title: "Список изменений",
        description: "Что нового в каждой версии Birchpad.",
        intro: ":::note\nСписок изменений ведётся на английском языке, как в репозитории проекта. Загрузки каждой версии — на [странице релизов](https://github.com/SecurityTrip/Birchpad/releases).\n:::",
      }
    : {
        title: "Changelog",
        description: "What is new in each version of Birchpad.",
        intro: "Downloads of each version are on the [releases page](https://github.com/SecurityTrip/Birchpad/releases).",
      };
  return `---\neditUrl: false\ntitle: ${yaml(head.title)}\ndescription: ${yaml(head.description)}\n---\n\n${GENERATED}\n\n${head.intro}\n\n${body.trim()}\n`;
}

// --- Keyboard shortcuts --------------------------------------------------------------------

const GROUPS = {
  file: ["File", "Файл"],
  edit: ["Edit", "Правка"],
  select: ["Selection", "Выделение"],
  cursor: ["Caret movement", "Перемещение курсора"],
  search: ["Search", "Поиск"],
  navigate: ["Navigation", "Навигация"],
  mark: ["Marks and token styles", "Пометки и стили"],
  bookmark: ["Bookmarks", "Закладки"],
  view: ["View", "Вид"],
  macro: ["Macro", "Макросы"],
  completion: ["Auto-completion", "Автодополнение"],
};
const CONTEXTS = {
  FindBar: ["in the find panel", "в панели поиска"],
  IncrementalBar: ["in incremental search", "в пошаговом поиске"],
  Completion: ["while the completion list shows", "в списке автодополнения"],
  CallTip: ["while a call tip shows", "в подсказке параметров"],
};

const KEY_NAMES = {
  pagedown: "PgDn", pageup: "PgUp", escape: "Esc", backspace: "Backspace", delete: "Del",
  insert: "Ins", enter: "Enter", tab: "Tab", space: "Space", left: "←", right: "→", up: "↑",
  down: "↓", home: "Home", end: "End", add: "Num +", subtract: "Num −", divide: "Num /",
};

function formatKeys(keys, mac) {
  return keys.split(" ").map((stroke) => {
    // "secondary--" is Ctrl and the minus key: split off the modifiers only.
    const parts = stroke.match(/^((?:(?:secondary|ctrl|alt|shift|cmd)-)*)(.+)$/);
    const mods = parts[1].split("-").filter(Boolean);
    const key = parts[2];
    const name = KEY_NAMES[key] || (key.length === 1 ? key.toUpperCase() : key.toUpperCase());
    const mod = (m) => {
      if (m === "secondary") return mac ? "⌘" : "Ctrl";
      if (m === "cmd") return "⌘";
      if (mac) return { ctrl: "⌃", alt: "⌥", shift: "⇧" }[m];
      return { ctrl: "Ctrl", alt: "Alt", shift: "Shift" }[m];
    };
    const all = [...mods.map(mod), name].map((k) => `<kbd>${k}</kbd>`);
    return all.join(mac ? "" : "+");
  }).join(" ");
}

function shortcuts(keymap, en, ru, lang) {
  // Titles come from the interface's locales: `command.<group>.<name>` for the id
  // `<group>.<name>`, Russian where translated, else English.
  const locales = [YAML.parse(lang === "ru" ? ru : en), YAML.parse(en)];
  const titleOf = (id) => {
    const dot = id.indexOf(".");
    for (const l of locales) {
      const t = l.command?.[id.slice(0, dot)]?.[id.slice(dot + 1)];
      if (typeof t === "string") return t;
    }
    return id;
  };
  const L = lang === "ru" ? 1 : 0;

  // One row per command and arguments, with its keys on each platform.
  const rows = new Map();
  for (const b of parse(keymap).binding) {
    const group = b.command.split(".")[0];
    const args = b.args ? Object.values(b.args).join(", ") : "";
    const id = `${b.command}|${args}|${b.context || ""}`;
    if (!rows.has(id)) {
      let name = titleOf(b.command).replace(/\.\.\.$/, "…");
      if (args) name += ` (${args})`;
      if (CONTEXTS[b.context]) name += ` — <em>${CONTEXTS[b.context][L]}</em>`;
      rows.set(id, { group, name, command: b.command, win: [], mac: [] });
    }
    const row = rows.get(id);
    const platforms = b.platforms || ["windows", "linux", "macos"];
    if (platforms.some((p) => p !== "macos")) row.win.push(formatKeys(b.keys, false));
    if (platforms.includes("macos")) row.mac.push(formatKeys(b.keys, true));
  }

  const head = lang === "ru"
    ? ["Сочетания клавиш", "Все сочетания клавиш Birchpad по умолчанию для Windows, Linux и macOS.",
       "Это сочетания по умолчанию. Их можно поменять в **Опции → Горячие клавиши…** или в файле `keymap.toml` — см. [Настройки](/docs/settings/#сочетания-клавиш). Таблица собирается из исходного кода Birchpad и соответствует его последней версии.",
       ["Команда", "Windows и Linux", "macOS"]]
    : ["Keyboard shortcuts", "Every default keyboard shortcut of Birchpad on Windows, Linux and macOS.",
       "These are the defaults. Change them in **Settings → Shortcut Mapper…** or in `keymap.toml` — see [Settings](/en/docs/settings/#keyboard-shortcuts). The table is built from Birchpad's source code and follows its latest version.",
       ["Command", "Windows and Linux", "macOS"]];
  let out = `---\neditUrl: false\ntitle: ${yaml(head[0])}\ndescription: ${yaml(head[1])}\n---\n\n${GENERATED}\n\n${head[2]}\n`;
  for (const [group, names] of Object.entries(GROUPS)) {
    const list = [...rows.values()].filter((r) => r.group === group);
    if (!list.length) continue;
    out += `\n## ${names[L]}\n\n| ${head[3].join(" | ")} |\n|---|---|---|\n`;
    for (const r of list) {
      out += `| ${cell(r.name)} | ${r.win.join(", ") || "—"} | ${r.mac.join(", ") || "—"} |\n`;
    }
  }
  const other = [...rows.values()].filter((r) => !GROUPS[r.group]);
  if (other.length) {
    out += `\n## ${lang === "ru" ? "Другое" : "Other"}\n\n| ${head[3].join(" | ")} |\n|---|---|---|\n`;
    for (const r of other) out += `| ${cell(r.name)} | ${r.win.join(", ") || "—"} | ${r.mac.join(", ") || "—"} |\n`;
  }
  return out;
}

// --- Languages -----------------------------------------------------------------------------

function plural(n, one, few, many) {
  const d = n % 10, h = n % 100;
  return d === 1 && h !== 11 ? one : d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
}

function languages(source, lang) {
  // Languages that only appear inside others (Markdown's inline part, JSDoc) come after EMBEDDED.
  const end = source.indexOf("static EMBEDDED");
  if (end > 0) source = source.slice(0, end);
  const re = /lang\(\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*&\[([^\]]*)\]/g;
  const list = [...source.matchAll(re)].map((m) => ({
    id: m[1],
    name: m[2],
    ext: m[4].split(",").map((e) => e.trim().replace(/"/g, "")).filter(Boolean),
  }));
  const ru = lang === "ru";
  let out = `---\neditUrl: false\ntitle: ${yaml(ru ? "Языки" : "Languages")}\ndescription: ${yaml(ru
    ? `${list.length} ${plural(list.length, "язык", "языка", "языков")} с подсветкой синтаксиса и сворачиванием в Birchpad.`
    : `${list.length} languages with syntax highlighting and folding in Birchpad.`)}\n---\n\n${GENERATED}\n\n`;
  out += ru
    ? `Birchpad подсвечивает и сворачивает код ${list.length} ${plural(list.length, "языка", "языков", "языков")} с помощью грамматик [tree-sitter](https://tree-sitter.github.io/). Разбор идёт в фоне и обновляется по мере правки, поэтому большие файлы не тормозят набор.

## Как определяется язык

По порядку: выбор в меню **Синтаксис**, имя файла (\`Makefile\`, \`.bashrc\`), расширение, строка \`#!\` в начале (\`#!/usr/bin/env python3\`) и сама первая строка (\`<?xml\`). Язык можно задать и из командной строки: \`birchpad -lpython file.txt\`. Файлам больше \`files.large-file-limit-mb\` (по умолчанию 20 МБ) подсветка не включается, как в Notepad++.

## Вложенные языки

Один документ может содержать несколько языков, и каждый подсвечивается своей грамматикой: скрипты и стили в HTML и Svelte, блоки кода, разметка и front matter в Markdown, HTML вокруг PHP, шаблонные строки, регулярные выражения и JSDoc в JavaScript и TypeScript.

## Свои языки

Для языков, которых нет в списке, подключите пользовательский язык Notepad++ (UDL) — см. [Свои языки и автодополнение](/docs/udl-and-completion/).

## Список языков

Идентификатор — это имя для ключа \`-l\` командной строки и для разделов \`[language.<id>]\` в темах.
`
    : `Birchpad highlights and folds ${list.length} languages with [tree-sitter](https://tree-sitter.github.io/) grammars. Parsing runs in the background and follows each edit, so large files do not slow typing down.

## How the language is chosen

In this order: the choice in the **Language** menu, the file name (\`Makefile\`, \`.bashrc\`), the extension, a \`#!\` first line (\`#!/usr/bin/env python3\`) and the first line itself (\`<?xml\`). The command line can set it too: \`birchpad -lpython file.txt\`. Files larger than \`files.large-file-limit-mb\` (20 MB by default) open without highlighting, as in Notepad++.

## Embedded languages

A document may hold several languages, each highlighted by its own grammar: scripts and styles in HTML and Svelte, code blocks, inline formatting and front matter in Markdown, HTML around PHP, tagged templates, regular expressions and JSDoc in JavaScript and TypeScript.

## Your own languages

For a language that is not listed, add a Notepad++ User Defined Language — see [User languages and auto-completion](/en/docs/udl-and-completion/).

## All languages

The id is the name for the \`-l\` command-line option and for \`[language.<id>]\` tables in themes.
`;
  out += `\n| ${ru ? "Язык" : "Language"} | ${ru ? "Идентификатор" : "Id"} | ${ru ? "Расширения" : "Extensions"} |\n|---|---|---|\n`;
  for (const l of list) {
    out += `| ${cell(l.name)} | \`${l.id}\` | ${l.ext.map((e) => `\`.${e}\``).join(" ") || "—"} |\n`;
  }
  return out;
}

// --- Run -----------------------------------------------------------------------------------

const jobs = [
  ["changelog.md", "en/changelog.md", async () => {
    const text = await source("CHANGELOG.md");
    return [changelog(text, "ru"), changelog(text, "en")];
  }],
  ["docs/shortcuts.md", "en/docs/shortcuts.md", async () => {
    const [keymap, en, ru] = await Promise.all([
      source("crates/commands/src/default-keymap.toml"),
      source("crates/app/locales/en.yaml"),
      source("crates/app/locales/ru.yaml"),
    ]);
    return [shortcuts(keymap, en, ru, "ru"), shortcuts(keymap, en, ru, "en")];
  }],
  ["docs/languages.md", "en/docs/languages.md", async () => {
    const text = await source("crates/syntax/src/language.rs");
    return [languages(text, "ru"), languages(text, "en")];
  }],
];

let failed = false;
for (const [ru, en, make] of jobs) {
  try {
    const [ruText, enText] = await make();
    await write(ru, ruText);
    await write(en, enText);
    console.log(`sync: ${ru}, ${en}`);
  } catch (error) {
    if ((await exists(ru)) && (await exists(en))) {
      console.warn(`sync: kept the previous ${ru} (${error.message})`);
    } else {
      console.error(`sync: ${ru}: ${error.message}`);
      failed = true;
    }
  }
}
if (failed) process.exit(1);
